def get_fips_coordinates(fips_code):
    """
    Get latitude and longitude for a FIPS code.
    
    Args:
        fips_code: String FIPS code (e.g., '06037')
        
    Returns:
        Tuple of (latitude, longitude) or None if not found
    """
    return FIPS_COORDS.get(str(fips_code).zfill(5))


def add_coordinates_to_dataframe(df, fips_column='fips'):
    """
    Add lat/lon columns to dataframe based on FIPS codes.
    For unknown FIPS codes, uses random coordinates within US bounds.
    
    Args:
        df: DataFrame with FIPS column
        fips_column: Name of the FIPS column
        
    Returns:
        DataFrame with added 'lat' and 'lon' columns
    """
    import numpy as np
    
    df = df.copy()
    
    # Try to map known FIPS codes
    coords = df[fips_column].astype(str).str.zfill(5).map(FIPS_COORDS)
    
    # For unknown FIPS, generate random coordinates within US bounds
    # but hash-based so same FIPS always gets same coords
    unknown_mask = coords.isna()
    
    if unknown_mask.any():
        rng = np.random.default_rng(42)
        unknown_fips = df.loc[unknown_mask, fips_column].unique()
        
        # Create deterministic coords for unknown FIPS
        fips_hash_coords = {}
        for fips in unknown_fips:
            # Use hash for deterministic randomness
            seed = int(str(abs(hash(str(fips))))[:8])
            temp_rng = np.random.default_rng(seed)
            # Continental US bounds
            lat = temp_rng.uniform(25.0, 49.0)
            lon = temp_rng.uniform(-125.0, -67.0)
            fips_hash_coords[fips] = (lat, lon)
        
        # Fill in unknown coords
        coords.loc[unknown_mask] = df.loc[unknown_mask, fips_column].map(fips_hash_coords)
    
    # Split into lat/lon
    df['lat'] = coords.apply(lambda x: x[0] if pd.notna(x) else None)
    df['lon'] = coords.apply(lambda x: x[1] if pd.notna(x) else None)
    
    return df
